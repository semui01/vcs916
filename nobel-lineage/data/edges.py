"""Curated connections between Nobel-recognised Physics contributions.

Direction: earlier contribution -> later contribution, ordered by the year of
the recognised WORK (not the award). Several edges therefore point from a
later award to an earlier one (award-order inversions); see analysis.

Relationship types (research brief, Step 2)
  TF  theoretical foundation
  EC  experimental confirmation (target confirms source's prediction, or
      source's data is what target's theory explained; see `claim`)
  IT  instrumental / technological foundation
  AE  new application or extension
  DF  direct discovery follow-up
  PD  independent parallel development (undirected in spirit; excluded from
      lineage paths and timing statistics)

Confidence (research brief, Step 3)
  H  explicitly stated by Nobel material or primary historical sources -> "documented"
  M  strongly supported by literature and history                     -> "strong inference"
  L  plausible but not established                                    -> "speculative"

scope: "direct" when the later work could not have happened in its actual
form without the earlier one; "ancestry" when the earlier work is part of
the background but not a material precondition.

verified: True only where the supporting statement was re-checked by web
search in this build session (nobelprize.org itself was unreachable; see
README). False means the citation is a standard Nobel or primary source given
from prior knowledge and should be checked before publication.
"""

